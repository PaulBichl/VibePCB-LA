"""Generate boards/<board>/ecp5_bg256.ts from Lattice's ECP5U-25 pinout CSV (tools/ecp5u25-pinout.csv,
latticesemi.com document 50485): ball -> function, bank, dual function, differential pair."""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

LETTERS = "ABCDEFGHJKLMNPRT"


def balls(csv_path: Path) -> dict[str, dict[str, str]]:
    rows = list(csv.reader(csv_path.open(encoding="latin-1")))
    hdr = next(i for i, r in enumerate(rows) if r and r[0] == "PAD")
    ci = rows[hdr].index("CABGA256")
    out = {}
    for r in rows[hdr + 1 :]:
        if len(r) > ci and r[ci].strip() not in ("", "-"):
            out[r[ci].strip()] = {"fn": r[1], "bank": r[2], "dual": r[3], "diff": r[4]}
    return out


def main() -> None:
    root = Path(__file__).resolve().parent
    target = Path(sys.argv[1])
    data = balls(root / "ecp5u25-pinout.csv")
    # tscircuit's imported footprint numbers balls column-major from A1: pin = col_index * 16 + row_index + 1
    pins = {b: LETTERS.index(b[0]) + (int(b[1:]) - 1) * 16 + 1 for b in data}
    target.write_text(
        "// generated by tools/ecp5_pinmap.py from Lattice's ECP5U-25 pinout (CABGA256) - do not edit\n"
        f"export const ECP5_BALLS = {json.dumps(data, indent=1)} as const\n"
        f"export const ECP5_PIN = {json.dumps(pins)} as const\n",
        encoding="utf-8",
    )


if __name__ == "__main__":
    main()
